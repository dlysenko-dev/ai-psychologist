FIRST_SESSION_INSTRUCTION = """ЭТО ПЕРВАЯ СЕССИЯ. ПРОВЕДИ INTAKE:
1. Представься кратко (2 предложения). Объясни что ты AI, не лицензированный терапевт.
2. Спроси о текущей ситуации: проекты, доход, что привело сюда.
3. Проведи скрининг денежных скриптов через разговор (не как формальный тест).
4. Задай вопросы из Monetization Block Screening (встроенные в диалог).
5. Резюмируй наблюдения и предложи фокус для следующих сессий.
6. Назначь 2-3 микро-задания.

Будь тёплым, но профессиональным. Не перегружай — 3-4 вопроса за раз максимум."""


def build_system_prompt(
    session_number: int = 1,
    therapy_phase: str = "assessment",
    total_sessions: int = 0,
    money_scripts_summary: str = "Не определены",
    active_tasks: str = "Нет",
    patterns: str = "Не выявлены",
    last_session_summary: str = "Первая сессия",
    session_focus: str = "Intake и первичная оценка",
    methodology: str | None = None,
    rag_context: str = "",
) -> str:
    """Assemble the full system prompt from components."""
    parts = [CORE_IDENTITY]

    # Session context
    context = SESSION_CONTEXT_TEMPLATE.format(
        session_number=session_number,
        therapy_phase=therapy_phase,
        total_sessions=total_sessions,
        money_scripts_summary=money_scripts_summary,
        active_tasks=active_tasks,
        patterns=patterns,
        last_session_summary=last_session_summary,
        session_focus=session_focus,
    )
    parts.append(context)

    # Methodology instructions
    if methodology and methodology in METHODOLOGY_INSTRUCTIONS:
        parts.append(METHODOLOGY_INSTRUCTIONS[methodology])

    # First session special instructions
    if session_number == 1 and total_sessions == 0:
        parts.append(FIRST_SESSION_INSTRUCTION)

    # RAG context
    if rag_context:
        parts.append(
            f"\nРЕЛЕВАНТНЫЙ КОНТЕКСТ ИЗ БАЗЫ ЗНАНИЙ:\n{rag_context}"
        )

    return "\n\n".join(parts)
